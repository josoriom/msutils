use crate::utilities::find_features::dedup_points;

const MZ_TOLERANCE: f64 = 0.003;
const PPM_TOLERANCE: f64 = 10.0;
const RT_TOLERANCE: f64 = 0.1;

#[cfg(test)]
fn dedup(points: Vec<(f64, f64, f64)>) -> Vec<(f64, f64, f64)> {
    dedup_points(points, MZ_TOLERANCE, PPM_TOLERANCE, RT_TOLERANCE)
}

#[test]
fn empty_returns_empty() {
    assert!(dedup(vec![]).is_empty());
}

#[test]
fn single_point_passes_through() {
    let result = dedup(vec![(0.945, 758.567, 652890.0)]);
    assert_eq!(result.len(), 1);
}

